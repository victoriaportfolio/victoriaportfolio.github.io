let scrollQueued = false;
function updateReadingProgress() {
  const total = document.documentElement.scrollHeight-innerHeight;
  document.getElementById('reading-progress').style.width = `${total>0?Math.min(100,Math.max(0,scrollY/total*100)):0}%`;
  scrollQueued = false;
}
addEventListener('scroll',()=>{if(!scrollQueued){scrollQueued=true;requestAnimationFrame(updateReadingProgress);}},{passive:true});
addEventListener('resize',updateReadingProgress);
renderCase();
if(location.hash) requestAnimationFrame(()=>document.getElementById(location.hash.slice(1))?.scrollIntoView());
addEventListener('load',updateReadingProgress,{once:true});
